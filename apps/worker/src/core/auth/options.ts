// Better Auth configuration (from the T00 spike). Shared by the Worker, the schema
// guard test and the /auth routes.
import type { BetterAuthOptions, BetterAuthPlugin } from "better-auth";
import { createAuthEndpoint, sessionMiddleware } from "better-auth/api";
import { parseCookies } from "better-auth/cookies";
import { jwt, multiSession } from "better-auth/plugins";
import { oauthProvider } from "@better-auth/oauth-provider";
import { passkey } from "@better-auth/passkey";
import { expo } from "@better-auth/expo";
import { ulid } from "@assistant/shared";

export const AUTH_BASE_PATH = "/auth";
export const MCP_PATH = "/mcp";
export const OAUTH_SCOPES = ["openid", "profile", "email", "offline_access"];
/** Accounts one device stays signed in to (docs/design/chats-home.md 7, the account switcher). */
export const ACCOUNTS_PER_DEVICE = 5;

/**
 * The account switcher keeps each account's session in its own signed cookie (Better Auth's
 * multi-session plugin), set when someone signs in. People signed in before it existed have
 * none, so adding a second account would push their first one out; the app calls this first
 * (`POST /auth/multi-session/keep`): it keeps the current session the same way. Nothing else.
 */
function keepThisAccount() {
  return {
    id: "keep-this-account",
    endpoints: {
      keepThisAccount: createAuthEndpoint(
        "/multi-session/keep",
        { method: "POST", requireHeaders: true, use: [sessionMiddleware] },
        async (ctx) => {
          const config = ctx.context.authCookies.sessionToken;
          const token = ctx.context.session.session.token;
          const name = `${config.name}_multi-${token.toLowerCase()}`;
          const cookies = parseCookies(ctx.headers?.get("cookie") ?? "");
          if (cookies.has(name)) return ctx.json({ kept: true });
          const kept = [...cookies.keys()].filter((k) => k.includes("_multi-")).length;
          if (kept >= ACCOUNTS_PER_DEVICE) return ctx.json({ kept: false });
          await ctx.setSignedCookie(name, token, ctx.context.secret, config.attributes);
          return ctx.json({ kept: true });
        },
      ),
    },
  } satisfies BetterAuthPlugin;
}

export interface AuthConfig {
  baseURL: string;
  secret: string;
  database: BetterAuthOptions["database"];
  google?: { clientId: string; clientSecret: string };
  /** Tests and localhost only: email/password so flows can run without Google. */
  emailAndPassword?: boolean;
}

export function authOptions(cfg: AuthConfig) {
  const mcpUrl = new URL(MCP_PATH, cfg.baseURL).toString();
  const url = new URL(cfg.baseURL);
  return {
    baseURL: cfg.baseURL,
    basePath: AUTH_BASE_PATH,
    secret: cfg.secret,
    database: cfg.database,
    advanced: { database: { generateId: () => ulid() } },
    emailAndPassword: { enabled: cfg.emailAndPassword ?? false },
    socialProviders: cfg.google
      ? {
          google: {
            clientId: cfg.google.clientId,
            clientSecret: cfg.google.clientSecret,
            // Google asks which account each time, so "Add another account" can pick a new one.
            prompt: "select_account",
          },
        }
      : {},
    // The phone app (apps/mobile): its deep-link scheme may receive sign-in redirects, and the
    // session cookie travels as a header (phones don't keep cookies reliably).
    trustedOrigins: ["gigspree://"],
    plugins: [
      expo(),
      passkey({ rpID: url.hostname, rpName: "Gigspree", origin: url.origin }),
      // JWTs are for MCP connectors (the OAuth provider signs them with the JWKS key). The
      // app's own calls read the session cookie, so get-session doesn't sign one: that kept
      // every signed-in request from crashing when the key couldn't be read (2026-10-24, the
      // auth secret regenerated by a deploy; decision "The auth secret is never regenerated").
      jwt({ disableSettingJwtHeader: true }),
      // Several accounts on one device, switched with one tap (chats-home.md 7).
      multiSession({ maximumSessions: ACCOUNTS_PER_DEVICE }),
      keepThisAccount(),
      oauthProvider({
        loginPage: "/login",
        consentPage: "/consent",
        scopes: OAUTH_SCOPES,
        allowDynamicClientRegistration: true,
        allowUnauthenticatedClientRegistration: true,
        resources: [mcpUrl],
        clientRegistrationDefaultResources: [mcpUrl],
      }),
    ],
  } satisfies BetterAuthOptions;
}
