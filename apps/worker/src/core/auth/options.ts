// Better Auth configuration (from the T00 spike). Shared by the Worker, the schema
// guard test and the /auth routes.
import type { BetterAuthOptions } from "better-auth";
import { jwt } from "better-auth/plugins";
import { oauthProvider } from "@better-auth/oauth-provider";
import { passkey } from "@better-auth/passkey";
import { expo } from "@better-auth/expo";
import { ulid } from "@assistant/shared";

export const AUTH_BASE_PATH = "/auth";
export const MCP_PATH = "/mcp";
export const OAUTH_SCOPES = ["openid", "profile", "email", "offline_access"];

export interface AuthConfig {
  baseURL: string;
  secret: string;
  database: BetterAuthOptions["database"];
  google?: { clientId: string; clientSecret: string };
  /** Tests and localhost only: email/password so flows can run without Google. */
  emailAndPassword?: boolean;
}

export function authOptions(cfg: AuthConfig) {
  const mcpUrl = new URL(MCP_PATH, cfg.baseURL).toString();
  const url = new URL(cfg.baseURL);
  return {
    baseURL: cfg.baseURL,
    basePath: AUTH_BASE_PATH,
    secret: cfg.secret,
    database: cfg.database,
    advanced: { database: { generateId: () => ulid() } },
    emailAndPassword: { enabled: cfg.emailAndPassword ?? false },
    socialProviders: cfg.google
      ? { google: { clientId: cfg.google.clientId, clientSecret: cfg.google.clientSecret } }
      : {},
    // The phone app (apps/mobile): its deep-link scheme may receive sign-in redirects, and the
    // session cookie travels as a header (phones don't keep cookies reliably).
    trustedOrigins: ["gigspree://"],
    plugins: [
      expo(),
      passkey({ rpID: url.hostname, rpName: "Gigspree", origin: url.origin }),
      // JWTs are for MCP connectors (the OAuth provider signs them with the JWKS key). The
      // app's own calls read the session cookie, so get-session doesn't sign one: that kept
      // every signed-in request from crashing when the key couldn't be read (2026-10-24, the
      // auth secret regenerated by a deploy; decision "The auth secret is never regenerated").
      jwt({ disableSettingJwtHeader: true }),
      oauthProvider({
        loginPage: "/login",
        consentPage: "/consent",
        scopes: OAUTH_SCOPES,
        allowDynamicClientRegistration: true,
        allowUnauthenticatedClientRegistration: true,
        resources: [mcpUrl],
        clientRegistrationDefaultResources: [mcpUrl],
      }),
    ],
  } satisfies BetterAuthOptions;
}
