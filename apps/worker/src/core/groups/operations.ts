// Group chats (chat-first step 7): in the app only (never API tokens or MCP).
import { z } from "zod";
import {
  AddGroupPeopleInput,
  AskInGroupInput,
  ShareAnswerInput,
  CreateGroupInput,
  GetGroupInput,
  GroupMessageRef,
  GroupRef,
  MarkSavedInput,
  PostGroupMessageInput,
} from "@assistant/shared";
import { defineOperation, type AnyOperation } from "../operations.ts";
import {
  addGroupPeople,
  askInGroup,
  groupAssistant,
  shareAnswer,
  chatPeople,
  createGroup,
  groupView,
  leaveGroup,
  markGroupMessageSaved,
  markGroupRead,
  myGroups,
  saveGroupMessage,
  postGroupMessage,
} from "./service.ts";

export function groupOperations(all: () => readonly AnyOperation[]) {
  return [
    defineOperation({
      id: "core.list_groups",
      tool: "list_groups",
      description: "My group chats.",
      kind: "read",
      sessionOnly: true,
      http: { method: "GET", path: "/groups" },
      input: z.object({}),
      handler: (ctx) => myGroups(ctx),
    }),
    defineOperation({
      id: "core.list_chat_people",
      tool: "list_chat_people",
      description: "People I can start a chat with.",
      kind: "read",
      sessionOnly: true,
      http: { method: "GET", path: "/chat-people" },
      input: z.object({}),
      handler: (ctx) => chatPeople(ctx),
    }),
    defineOperation({
      id: "core.read_group",
      tool: "read_group",
      description: "Mark a chat as read up to now.",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/read" },
      input: GroupRef,
      handler: (ctx, i) => markGroupRead(ctx, i.group_id),
    }),
    defineOperation({
      id: "core.create_group",
      tool: "create_group",
      description: "Make a group chat with people I know, or a chat with one person (direct).",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups", status: 201 },
      input: CreateGroupInput,
      handler: (ctx, i) => createGroup(ctx, i),
    }),
    defineOperation({
      id: "core.get_group",
      tool: "get_group",
      description: "A group chat and its newest messages.",
      kind: "read",
      sessionOnly: true,
      http: { method: "GET", path: "/groups/:group_id" },
      input: GetGroupInput,
      handler: (ctx, i) => groupView(ctx, i.group_id, i.around),
    }),
    defineOperation({
      id: "core.post_group_message",
      tool: "post_group_message",
      description: "Write in a group chat.",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/messages" },
      input: PostGroupMessageInput,
      handler: (ctx, i) => postGroupMessage(ctx, i.group_id, i.text),
    }),
    defineOperation({
      id: "core.group_assistant",
      tool: "group_assistant",
      description: "My own assistant chat about a group chat (only I see it).",
      kind: "read",
      sessionOnly: true,
      http: { method: "GET", path: "/groups/:group_id/assistant" },
      input: GroupRef,
      handler: (ctx, i) => groupAssistant(ctx, i.group_id),
    }),
    defineOperation({
      id: "core.ask_in_group",
      tool: "ask_in_group",
      description: "Ask my own assistant about a group chat (only I see it).",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/assistant" },
      input: AskInGroupInput,
      handler: (ctx, i) => askInGroup(ctx, all(), i.group_id, i),
    }),
    defineOperation({
      id: "core.share_answer",
      tool: "share_answer",
      description: "Share one of my assistant's answers into the group chat.",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/share" },
      input: ShareAnswerInput,
      handler: (ctx, i) => shareAnswer(ctx, i.group_id, i.item_id),
    }),
    defineOperation({
      id: "core.save_group_message",
      tool: "save_group_message",
      description:
        "Ask my assistant where a chat message should be saved; it proposes, nothing is saved yet.",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/messages/:message_id/save" },
      input: GroupMessageRef,
      handler: (ctx, i) => saveGroupMessage(ctx, all(), i.group_id, i.message_id),
    }),
    defineOperation({
      id: "core.mark_group_message_saved",
      tool: "mark_group_message_saved",
      description: "Remember that I saved a chat message, and where to.",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/messages/:message_id/saved" },
      input: MarkSavedInput,
      handler: (ctx, i) => markGroupMessageSaved(ctx, i.group_id, i.message_id, i.label),
    }),
    defineOperation({
      id: "core.add_group_people",
      tool: "add_group_people",
      description: "Add people I know to my group chat.",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/people" },
      input: AddGroupPeopleInput,
      handler: (ctx, i) => addGroupPeople(ctx, i.group_id, i.people),
    }),
    defineOperation({
      id: "core.leave_group",
      tool: "leave_group",
      description: "Leave a group chat.",
      kind: "write",
      sessionOnly: true,
      http: { method: "POST", path: "/groups/:group_id/leave" },
      input: GroupRef,
      handler: (ctx, i) => leaveGroup(ctx, i.group_id),
    }),
  ];
}
